// Builds the "microphone" recording: 2 s of room silence, the spoken phrase, then 2.5 s of silence (so the end of speech is detected).
// Chromium's fake audio device wants a plain 48 kHz 16-bit WAV, so the 16 kHz speech is resampled up (stereo if asked).
const fs = require('fs')
const V = require('../renderer/voice-core.js')
const [src, out, channelsArg] = process.argv.slice(2)
const channels = Number(channelsArg || 1)
const wav = fs.readFileSync(src)
const rate = wav.readUInt32LE(24)
const data = wav.subarray(44)
const speech = new Float32Array(data.length / 2)
for (let i = 0; i < speech.length; i++) speech[i] = data.readInt16LE(i * 2) / 0x8000
const noise = (secs) => Float32Array.from({ length: Math.round(rate * secs) }, () => (Math.random() - 0.5) * 0.0012)
const joined = new Float32Array(noise(2.0).length + speech.length + noise(2.5).length)
joined.set(noise(2.0), 0)
joined.set(speech, noise(2.0).length)
joined.set(noise(2.5), noise(2.0).length + speech.length)
const up = V.resample(joined, rate, 48000)
const pcm = Buffer.alloc(up.length * 2 * channels)
for (let i = 0; i < up.length; i++) for (let c = 0; c < channels; c++) pcm.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(up[i] * 32767))), (i * channels + c) * 2)
const header = Buffer.alloc(44)
header.write('RIFF', 0)
header.writeUInt32LE(36 + pcm.length, 4)
header.write('WAVEfmt ', 8)
header.writeUInt32LE(16, 16)
header.writeUInt16LE(1, 20)
header.writeUInt16LE(channels, 22)
header.writeUInt32LE(48000, 24)
header.writeUInt32LE(48000 * 2 * channels, 28)
header.writeUInt16LE(2 * channels, 32)
header.writeUInt16LE(16, 34)
header.write('data', 36)
header.writeUInt32LE(pcm.length, 40)
fs.writeFileSync(out, Buffer.concat([header, pcm]))
console.log(`wrote ${out}: ${(up.length / 48000).toFixed(1)} s, 48 kHz, ${channels} ch`)
